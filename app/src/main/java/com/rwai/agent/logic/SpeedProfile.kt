package com.rwai.agent.logic

/**
 * Профиль скорости агента. Каждый шаг агента — это вызов модели, и режим рассуждения (thinking) делает его в разы медленнее,
 * а длинная история экранов в запросе замедляет ещё сильнее. Поэтому по умолчанию рассуждение выключено, а история короче.
 */
object SpeedProfile {
    /** Сколько знаков истории (экраны и результаты инструментов) уходит модели на каждом шаге. */
    const val HISTORY_CHARS = 30_000

    /** Один раз выключаем рассуждение и на уже настроенных телефонах; дальше выбор владельца в настройках сохраняется. */
    fun thinkingAfterMigration(alreadyMigrated: Boolean, saved: Boolean): Boolean = if (alreadyMigrated) saved else false
}
